const SETTINGS_TRANSLATIONS: Record<SettingsLanguage, Record<SettingsI18nKey, string>> = {
  en: SETTINGS_EN,
  de: SETTINGS_DE,
};

export const tSettings = (language: SettingsLanguage, key: SettingsI18nKey): string => {
  const selected = SETTINGS_TRANSLATIONS[language]?.[key];
  return selected ?? SETTINGS_EN[key];
};

export const formatSettingsText = (
  language: SettingsLanguage,
  key: SettingsI18nKey,
  params: Record<string, string | number>,
) => {
  const template = tSettings(language, key);
  return Object.entries(params).reduce(
    (text, [name, value]) => text.split(`{${name}}`).join(String(value)),
    template,
  );
};

export const resolveSettingsNavModel = (
  language: SettingsLanguage,
): SettingsNavEntry[] => {
  return SETTINGS_NAV_MODEL.map((entry) => {
    if (entry.type === "divider") {
      const key = NAV_DIVIDER_KEYS[entry.label];
      return {
        ...entry,
        label: key ? tSettings(language, key) : entry.label,
      };
    }

    const labelKey = NAV_ITEM_LABEL_KEYS[entry.id];
    const titleKey = NAV_ITEM_TITLE_KEYS[entry.id];

    return {
      ...entry,
      label: labelKey ? tSettings(language, labelKey) : entry.label,
      title:
        titleKey && entry.title
          ? tSettings(language, titleKey)
          : entry.title,
      subPages: entry.subPages?.map((subPage) => {
        const subPageKey = NAV_SUBPAGE_LABEL_KEYS[subPage.id];
        return {
          ...subPage,
          label: subPageKey ? tSettings(language, subPageKey) : subPage.label,
        };
      }),
    };
  });
};

